"""Dataset loaders for benchmark datasets in robust statistics."""

from __future__ import annotations

import csv
from importlib import resources
from typing import Any, Tuple, Union

import numpy as np
from sklearn.utils import Bunch


def _read_data_file(filename: str) -> tuple[list[str], np.ndarray]:
    """Read a bundled CSV file into headers and float array."""
    data_file = resources.files("evolutionary_ml.datasets").joinpath("data", filename)
    with data_file.open("r", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = [list(map(float, row)) for row in reader if row]
    return header, np.asarray(rows, dtype=np.float64)


def _load_csv_dataset(
    filename: str,
    target_column: str,
    outlier_indices: list[int],
    descr: str,
    return_X_y: bool = False,
    as_frame: bool = False,
    extra_bunch_attrs: dict[str, Any] | None = None,
) -> Union[Bunch, Tuple[Any, Any]]:
    header, raw_array = _read_data_file(filename)
    if target_column not in header:
        raise ValueError(f"Target column '{target_column}' not found in headers {header}.")

    target_idx = header.index(target_column)
    feature_indices = [i for i in range(len(header)) if i != target_idx]
    feature_names = [header[i] for i in feature_indices]
    target_name = [header[target_idx]]

    X = raw_array[:, feature_indices]
    y = raw_array[:, target_idx]

    frame = None
    if as_frame:
        try:
            import pandas as pd
        except ImportError as err:
            raise ImportError(
                "pandas is required when as_frame=True. Please install pandas or set as_frame=False."
            ) from err

        data_df = pd.DataFrame(X, columns=feature_names)
        target_s = pd.Series(y, name=target_column)
        frame = pd.concat([data_df, target_s], axis=1)
        if return_X_y:
            return data_df, target_s

    if return_X_y:
        return X, y

    bunch_dict = {
        "data": X if not as_frame else data_df,
        "target": y if not as_frame else target_s,
        "feature_names": feature_names,
        "target_names": target_name,
        "outlier_indices": list(outlier_indices),
        "DESCR": descr.strip(),
        "frame": frame,
    }
    if extra_bunch_attrs:
        bunch_dict.update(extra_bunch_attrs)

    return Bunch(**bunch_dict)


def load_hbk(
    return_X_y: bool = False, as_frame: bool = False
) -> Union[Bunch, Tuple[Any, Any]]:
    r"""Load the Hawkins-Bradu-Kass (HBK) artificial benchmark dataset.

    Parameters
    ----------
    return_X_y : bool, default=False
        If True, returns ``(data, target)`` instead of a :class:`~sklearn.utils.Bunch` object.
    as_frame : bool, default=False
        If True, the data is a pandas DataFrame including columns with appropriate dtypes.

    Returns
    -------
    data : :class:`~sklearn.utils.Bunch`
        Dictionary-like object with attributes:
        - ``data``: ndarray of shape (75, 3).
        - ``target``: ndarray of shape (75,).
        - ``feature_names``: list of feature names ['X1', 'X2', 'X3'].
        - ``target_names``: ['Y'].
        - ``outlier_indices``: list of all 14 leverage point indices [0..13].
        - ``bad_leverage_indices``: list of 10 bad leverage point indices [0..9].
        - ``good_leverage_indices``: list of 4 good leverage point indices [10..13].
        - ``DESCR``: full description of the dataset.
        - ``frame``: pandas DataFrame if ``as_frame=True``.

    References
    ----------
    Hawkins, D. M., Bradu, D., & Kass, G. V. (1984). Location of several outliers
    in multiple-regression data using elemental sets. Technometrics, 26(3), 197-208.
    """
    descr = """
Hawkins-Bradu-Kass (HBK) Artificial Dataset
===========================================

- Number of instances: 75
- Number of attributes: 3 explanatory variables (X1, X2, X3) and 1 response (Y)

The dataset was generated by Hawkins, Bradu, and Kass (1984) to illustrate the
severe masking effect in multiple regression. Observations 1-14 (0-based indices 0-13)
are leverage points:
- 0 to 9: Bad leverage points (drastically alter ordinary least squares).
- 10 to 13: Good leverage points (high leverage, but on the true clean regression plane).
- 14 to 74: Clean observations.

Classical OLS completely fails to identify the outliers due to masking. High-breakdown
estimators like Least Trimmed Squares (LTS) cleanly uncover all 14 leverage points.
"""
    return _load_csv_dataset(
        filename="hbk.csv",
        target_column="Y",
        outlier_indices=list(range(14)),
        descr=descr,
        return_X_y=return_X_y,
        as_frame=as_frame,
        extra_bunch_attrs={
            "bad_leverage_indices": list(range(10)),
            "good_leverage_indices": list(range(10, 14)),
        },
    )


def load_stars(
    return_X_y: bool = False, as_frame: bool = False
) -> Union[Bunch, Tuple[Any, Any]]:
    r"""Load the Hertzsprung-Russell Star Cluster CYG OB1 dataset.

    Parameters
    ----------
    return_X_y : bool, default=False
        If True, returns ``(data, target)``.
    as_frame : bool, default=False
        If True, the data is a pandas DataFrame.

    Returns
    -------
    data : :class:`~sklearn.utils.Bunch`

    References
    ----------
    Rousseeuw, P. J., & Leroy, A. M. (1987). Robust Regression and Outlier Detection.
    John Wiley & Sons, page 27.
    """
    descr = """
Star Cluster CYG OB1 (Hertzsprung-Russell Diagram)
=================================================

- Number of instances: 47
- Number of attributes: 1 explanatory variable (log.Te) and 1 response (log.light)

Astronomical data regarding the star cluster CYG OB1.
- log.Te: Logarithm of effective surface temperature.
- log.light: Logarithm of its light intensity (luminosity).

The majority of stars lie on the "main sequence". However, 4 observations
(0-based indices 10, 19, 29, 33; observations 11, 20, 30, 34 in 1-based indexing)
are giant stars that constitute extreme outliers from the linear main sequence.
"""
    return _load_csv_dataset(
        filename="starsCYG.csv",
        target_column="log.light",
        outlier_indices=[10, 19, 29, 33],
        descr=descr,
        return_X_y=return_X_y,
        as_frame=as_frame,
    )


